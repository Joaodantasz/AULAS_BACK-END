// Object (objetos
// Um obejto agrupa várias informações dentro de uma mesma variável, usando chave e valor

let pessoa = {
    nome: "João",
    idade: 16,
    cidade: "São Paulo"
};

console.log(pessoa.nome) // usar o ponto para buscar uma variável específica, não tudo.//
console.log(pessoa.idade)
console.log(pessoa.cidade)

let carro = {
    marca: "Toyota",
    modelo : "Corolla",
    ano: 2026
}

console.log(carro.marca)
console.log(carro.modelo)
console.log(carro.ano)
